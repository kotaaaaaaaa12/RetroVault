  const listeners = new Set();
  const storageKey = "retro-vault-language";
  let mode = "auto";
  try { mode = window.localStorage.getItem(storageKey) || "auto"; } catch {}
  if (!["auto", "en", "ja"].includes(mode)) mode = "auto";

  function resolveLanguage() {
    if (mode !== "auto") return mode;
    const preferred = window.navigator?.languages?.[0] || window.navigator?.language || "en";
    return /^ja(?:-|$)/i.test(preferred) ? "ja" : "en";
  }

  let language = resolveLanguage();
  function t(key, values = {}) {
    if (key === "runtimeError") return errorText(values.message);
    const template = messages[language][key] ?? messages.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
  }

  function apply(root = document) {
    if (document.documentElement) document.documentElement.lang = language;
    const attributes = { "data-i18n": null, "data-i18n-placeholder": "placeholder", "data-i18n-aria-label": "aria-label", "data-i18n-title": "title" };
    for (const [marker, attribute] of Object.entries(attributes)) {
      for (const element of root.querySelectorAll("[" + marker + "]")) {
        const value = t(element.getAttribute(marker));
        if (attribute) element.setAttribute(attribute, value);
        else element.textContent = value;
      }
    }
  }

  function setLanguage(value, persist = true) {
    mode = ["auto", "en", "ja"].includes(value) ? value : "auto";
    language = resolveLanguage();
    if (persist) {
      try { window.localStorage.setItem(storageKey, mode); } catch {}
    }
    apply();
    for (const listener of listeners) listener(language, mode);
  }

